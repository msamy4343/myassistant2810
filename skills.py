def get_current_personality():
    mode = state.get("mode", "عادي")
    return MODES.get(mode, MODES["عادي"])

def handle_mode_text(user_text):
    """لو طلب تغيير الوضع — يرجع رد — وإلا None"""
    text = user_text.strip()

    for mode_name in MODES:
        if f"وضع {mode_name}" in text or f"حط وضع {mode_name}" in text:
            state["mode"] = mode_name
            save("state", state)
            return f"🎭 اتحولت لوضع «{mode_name}»"

    if "الأوضاع" in text or "الاوضاع" in text:
        current = state.get("mode", "عادي")
        names = " / ".join(MODES.keys())
        return f"🎭 الوضع الحالي: {current}\nالمتاح: {names}\nغيّر بجملة: «حط وضع المدرس»"

    if "حط وضع" in text or "غير الوضع" in text:
        names = " / ".join(MODES.keys())
        return f"المتاح: {names}\nقول: «حط وضع المدرس» مثلاً"

    return None
